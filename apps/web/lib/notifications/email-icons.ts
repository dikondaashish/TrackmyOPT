export function emailIcon(
  name: EmailIconName,
  options?: { size?: number; color?: string }
): string {
  const size = options?.size ?? 16;
  const color = options?.color ?? "#374151";
  const paths = PATHS[name];
  return `<span style="display:inline-block;vertical-align:middle;margin-right:6px;line-height:0;"><svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="${color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${paths}</svg></span>`;
}

/** Section heading with inline icon for email HTML. */
export function emailSectionHeading(
  title: string,
  iconName: EmailIconName,
  color = "#1F2937"
): string {
  return `${emailIcon(iconName, { color })}<span style="vertical-align:middle;">${title}</span>`;
}
