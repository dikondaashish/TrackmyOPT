import type { BlogProductCtaVariant } from '@/components/blog/BlogProductCTA';
import type { BlogHubSlug } from '@/data/blog-hubs';

export type ArticleSource = {
  label: string;
  url: string;
  publisher: string;
};

export type ArticleTable = {
  caption?: string;
  columns: string[];
  rows: string[][];
};

export type ArticleLanguage = 'en' | 'es' | 'ko';

export type ArticleSection = {
  heading: string;
  paragraphs: string[];
  bullets?: string[];
  numbered?: string[];
  /** Rendered after the paragraphs and before any bullets. */
  table?: ArticleTable;
  /**
   * A static chart or diagram rendered by scripts/blog-figures/render-figure.mjs.
   * Keep the underlying numbers in a table too, so the figure is never the only
   * way to read them.
   */
  figure?: { src: string; alt: string; caption: string; width: number; height: number };
  note?: string;
  /** Preserve useful inbound fragment links when refreshing an existing guide. */
  anchors?: string[];
  sources?: ArticleSource[];
  links?: Array<{ label: string; href: string }>;
  visual?: {
    src: string;
    poster: string;
    alt: string;
    caption: string;
    steps: string[];
  };
};

export type ResearchArticle = {
  slug: string;
  title: string;
  seoTitle?: string;
  description: string;
  category: string;
  tags: string[];
  readTime: string;
  publishedDate: string;
  modifiedDate: string;
  directAnswer: string;
  keyTakeaways: string[];
  sections: ArticleSection[];
  checklist: string[];
  mistakes: string[];
  faq: Array<{ question: string; answer: string }>;
  sources: ArticleSource[];
  related: Array<{ label: string; href: string }>;
  cta: BlogProductCtaVariant;
  /** Topic hub (/blog/hub/<hub>) that lists this post. */
  hub?: BlogHubSlug;
  statusNote?: string;
  dataNote?: string;
  /** Describe the evidence actually reviewed for developing news. */
  reviewLabel?: string;
  badgeLabel?: string;
  /** Explicit editorial approval for the short-lived Google News sitemap. */
  newsSitemapEligible?: boolean;
  /** ISO timestamp used to remove an approved news article after 48 hours. */
  newsPublishedAt?: string;
  image?: string;
  imageAlt?: string;
  imageCaption?: string;
  showContents?: boolean;
  /** 'automated': generated by the policy-news cron and published without editorial review. */
  byline?: 'automated';
  /** Article language; defaults to English. Spanish articles localise the page chrome. */
  lang?: ArticleLanguage;
  /** Slugs of the same article in other languages, for hreflang alternates. */
  translations?: Partial<Record<ArticleLanguage, string>>;
};
