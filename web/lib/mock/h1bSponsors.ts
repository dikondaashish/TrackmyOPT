// Helper to determine sponsorship strength based on total LCA counts
function getStrength(count: number): "High" | "Medium" | "Low" {
    if (count >= 100) return "High";
    if (count >= 40) return "Medium";
    return "Low";
}

// Helper to determine company size
function getSize(count: number): "Startup" | "Mid" | "Enterprise" {
    if (count >= 100) return "Enterprise";
    if (count >= 50) return "Mid";
    return "Startup";
}

